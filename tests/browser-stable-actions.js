async(page)=>{
  const checks=[];
  const box=selector=>page.locator(selector).boundingBox();
  const same=(a,b,label)=>{if(!a||!b||Math.abs(a.y-b.y)>1||Math.abs(a.height-b.height)>1)throw Error(label+': controls moved');checks.push(label);};
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('http://127.0.0.1:4187/?auth_bypass=1');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('combobox',{name:'Learning language',exact:true}).selectOption('en');
  await page.getByRole('button',{name:'Today',exact:true}).click();
  await page.getByRole('button',{name:'Start today’s review',exact:true}).last().click();
  const reveal=await box('[data-action="flip"].primary');
  await page.getByRole('button',{name:'Show answer',exact:false}).click();
  same(reveal,await box('[data-action="pass"]'),'Reveal and self-rating share the same row');
  await page.locator('.review-example').evaluate(el=>el.textContent='A very long example sentence. '.repeat(120));
  same(reveal,await box('[data-action="pass"]'),'Long revealed content does not move rating');
  await page.evaluate(()=>window.scrollTo(0,document.body.scrollHeight));
  same(reveal,await box('[data-action="pass"]'),'Rating remains visible while scrolling');
  await page.getByRole('button',{name:'I knew it',exact:false}).click();
  same(reveal,await box('[data-action="flip"].primary'),'Next card keeps action position');
  await page.getByRole('button',{name:'Exit session',exact:false}).click();
  await page.getByRole('button',{name:'Leave session',exact:true}).click();
  await page.getByRole('heading',{name:'Today',exact:true}).waitFor();
  await page.locator('.customize>summary').click();
  await page.getByRole('combobox',{name:'Practice mode',exact:true}).selectOption('spelling');
  await page.getByRole('button',{name:'Start today’s review',exact:true}).last().click();
  const submit=await box('[form="answer-form"]');
  await page.getByRole('textbox',{name:'Your answer',exact:true}).fill('wrong_answer');
  await page.getByRole('button',{name:'Check answer',exact:false}).click();
  same(submit,await box('[form="answer-form"]'),'Wrong answer feedback does not move submit');
  await page.getByRole('button',{name:'I don’t know',exact:true}).click();
  same(submit,await box('[data-action="next-card"]'),'Continue occupies submit position');
  await page.getByRole('button',{name:'Continue',exact:false}).click();
  same(submit,await box('[form="answer-form"]'),'Spelling next card keeps submit position');
  await page.getByRole('textbox',{name:'Your answer',exact:true}).fill('wrong_answer');
  await page.getByRole('textbox',{name:'Your answer',exact:true}).press('Enter');
  if(!(await page.locator('#answer-feedback').textContent()).includes('Not quite'))throw Error('Enter submission broken');
  await page.evaluate(()=>{document.documentElement.classList.add('keyboard-open');document.documentElement.style.setProperty('--keyboard-inset','300px');});
  const keyboard=await box('[form="answer-form"]');
  if(keyboard.y+keyboard.height>544)throw Error('Action overlaps simulated keyboard');
  checks.push('Keyboard inset keeps task controls above keyboard');
  await page.screenshot({path:'output/playwright/review-keyboard-inset.png'});
  await page.evaluate(()=>{document.documentElement.classList.remove('keyboard-open');document.documentElement.style.setProperty('--keyboard-inset','0px');});
  const correct=await page.evaluate(async()=>{const {mockCards}=await import('./js/mock.js');const meaning=document.querySelector('.prompt-meaning').textContent;return mockCards('en').find(c=>c.meaning_zh===meaning).word_en;});
  const progress=await page.locator('.review-progress').textContent();
  await page.getByRole('textbox',{name:'Your answer',exact:true}).fill(correct);
  await page.getByRole('button',{name:'Check answer',exact:false}).click();
  await page.waitForFunction(before=>document.querySelector('.review-progress')?.textContent!==before,progress);
  same(submit,await box('[form="answer-form"]'),'Correct submission advances without moving controls');
  await page.getByRole('button',{name:'Exit session',exact:false}).click();
  await page.getByRole('button',{name:'Leave session',exact:true}).click();
  await page.getByRole('button',{name:'Library',exact:true}).click();
  const paging=await box('.pagination');
  await page.getByRole('button',{name:'Next page',exact:true}).click();
  same(paging,await box('.pagination'),'Pagination does not move on shorter page');
  await page.getByRole('button',{name:'Add word',exact:true}).click();
  const save=await box('#card-form [type="submit"]');
  for(let i=0;i<4;i++)await page.getByRole('button',{name:'Add another example'}).click();
  same(save,await box('#card-form [type="submit"]'),'Adding examples does not move Save');
  await page.locator('[name="note"]').evaluate(el=>el.style.height='450px');
  await page.getByRole('button',{name:'Save word',exact:false}).click();
  same(save,await box('#card-form [type="submit"]'),'Textarea growth and validation do not move Save');
  await page.evaluate(()=>window.scrollTo(0,document.body.scrollHeight));
  same(save,await box('#card-form [type="submit"]'),'Save remains visible at document bottom');
  const error=await box('#form-error'),dock=await box('#card-form>.form-actions');
  if(error.y+error.height>dock.y)throw Error('Action row covers validation message');
  checks.push('Reserved space keeps final form content above dock');
  await page.screenshot({path:'output/playwright/form-fixed-actions.png'});
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByRole('button',{name:'Today',exact:true}).click();
  console.log(JSON.stringify(checks));
}
