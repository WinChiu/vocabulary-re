async (page) => {
  await page.emulateMedia({reducedMotion:'reduce'});
  const results=[];const check=async(c,label)=>{if(!await c)throw Error(label);results.push(label);};
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Today',exact:true}).click();
  const details=page.locator('.customize');if(await details.evaluate(el=>el.open))await details.locator('summary').click();
  await page.screenshot({path:'output/playwright/today-mobile.png',fullPage:true});
  await check(page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Today mobile has no horizontal overflow');
  await check(page.locator('.page-heading').boundingBox().then(b=>b.height<70),'Today header is one compact line');
  await check(page.locator('.bottom-nav').boundingBox().then(b=>Math.abs(b.y+b.height-844)<2),'Navigation fixed to viewport bottom');
  await check(page.getByRole('combobox',{name:'Learning language'}).count().then(n=>n===0),'Language control removed from Today');
  await page.getByRole('button',{name:'Library',exact:true}).click();
  await page.getByRole('textbox',{name:'Search library'}).fill('');
  await page.screenshot({path:'output/playwright/library-mobile.png',fullPage:true});
  await check(page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Library mobile has no horizontal overflow');
  await check(page.locator('.page-heading').boundingBox().then(b=>b.height<70),'Library header keeps actions on one line');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('heading',{name:'Settings',exact:true}).waitFor();
  await check(page.getByRole('combobox',{name:'Learning language',exact:true}).isVisible(),'Language control in Settings');
  await check(page.getByRole('button',{name:'Sign out',exact:true}).isVisible(),'Sign out in Settings');
  await check(page.getByText('test-bypass@local',{exact:true}).isVisible(),'Account email visible');
  await page.screenshot({path:'output/playwright/settings-mobile.png',fullPage:true});
  await page.getByRole('combobox',{name:'Learning language',exact:true}).selectOption('sv');
  await check(page.getByRole('heading',{name:'Settings',exact:true}).isVisible(),'Language switch stays on Settings');
  await page.getByRole('button',{name:'Library',exact:true}).click();
  await check(page.locator('.word-row').count().then(n=>n===4),'Swedish word library isolated');
  await page.locator('.word-open').first().click();
  await check(page.getByRole('heading',{name:'fika',exact:true}).isVisible(),'Swedish detail');
  await check(page.locator('#dictionary-content').textContent().then(t=>t===''),'Swedish dictionary absent');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.reload();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await check(page.getByRole('combobox',{name:'Learning language',exact:true}).inputValue().then(v=>v==='sv'),'Learning language persists across reload');
  await page.getByRole('combobox',{name:'Learning language',exact:true}).selectOption('en');
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByRole('heading',{name:'Sign in',exact:true}).waitFor();
  await check(Promise.resolve(!page.url().includes('?')),'Bypass logout clears URL parameters');
  await check(page.locator('.bottom-nav').count().then(n=>n===0),'Signed-out screen has no app navigation');
  await page.screenshot({path:'output/playwright/login-mobile.png',fullPage:true});
  await page.getByRole('link',{name:'Try the demo',exact:false}).click();
  await page.getByRole('heading',{name:'Today',exact:true}).waitFor();
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'output/playwright/today-desktop.png',fullPage:true});
  console.log(JSON.stringify(results));
}
